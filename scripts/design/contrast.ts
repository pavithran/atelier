// The palette's contrast, measured from the tokens themselves (t499):
// `node scripts/design/contrast.ts` writes docs/design/contrast.md from
// src/theme.css and src/layout.css, and test/fixtures/design/contrast.test.ts
// fails when the file no longer matches them. This measures the colours the
// pages are built from, in Night (dark) and its light variant, against the
// four surfaces text sits on; it does not see a page. The browser audit
// (scripts/design/audit.ts, docs/design/audit.json) measures rendered text.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));

// The text and mark colours, with what each is for, and the surfaces.
export const FOREGROUNDS: [token: string, role: string][] = [
  ["--text", "body text"], ["--text-bright", "headings, strong"], ["--text-muted", "secondary text (43 rules)"], ["--text-dim", "meta, captions"],
  ["--signal", "links, owner's colour"], ["--signal-hot", "focus ring, hover"], ["--observed", "passed, merged"], ["--caution", "waiting, warning"], ["--fault", "failed, sent back"],
  ["--m-anthropic", "Claude family"], ["--m-openai", "GPT family"], ["--m-zai", "GLM family"], ["--m-google", "Gemini family"], ["--m-qwen", "Qwen family"], ["--main-line", "main line on graphs"],
];
export const SURFACES: [token: string, role: string][] = [["--surface", "page"], ["--surface-raised", "sheet, card"], ["--inset", "selected row, tag"], ["--shell", "rail"]];

// The custom properties a block declares: the first `:root {` block of a
// file, or the `:root` block inside the first `@media (prefers-color-scheme: light)`.
function block(css: string, light: boolean): Map<string, string> {
  let text = css;
  if (light) {
    const at = css.indexOf("@media (prefers-color-scheme: light)");
    text = css.slice(css.indexOf(":root", at));
  } else text = css.slice(css.indexOf(":root"));
  const body = text.slice(text.indexOf("{") + 1, text.indexOf("}"));
  return new Map([...body.matchAll(/(--[a-z0-9-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
}

function resolve(vars: Map<string, string>, token: string, depth = 0): string {
  const v = vars.get(token);
  if (!v) throw new Error(`no ${token}`);
  const ref = /^var\((--[a-z0-9-]+)\)$/.exec(v);
  return ref && depth < 5 ? resolve(vars, ref[1], depth + 1) : v;
}

const channel = (hex: string, i: number) => parseInt(hex.slice(1 + 2 * i, 3 + 2 * i), 16) / 255;
export function luminance(hex: string): number {
  const lin = (s: number) => (s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4);
  return 0.2126 * lin(channel(hex, 0)) + 0.7152 * lin(channel(hex, 1)) + 0.0722 * lin(channel(hex, 2));
}
export function ratio(a: string, b: string): number {
  const [x, y] = [luminance(a), luminance(b)].sort((p, q) => q - p);
  return Math.round(((x + 0.05) / (y + 0.05)) * 100) / 100;
}

export interface Row { scheme: "dark" | "light"; token: string; role: string; hex: string; ratios: Record<string, number> }

export function measure(theme: string, layout: string): Row[] {
  const rows: Row[] = [];
  for (const scheme of ["dark", "light"] as const) {
    const vars = new Map([...block(theme, false), ...block(layout, false)]);
    if (scheme === "light") for (const [k, v] of [...block(theme, true), ...block(layout, true)]) vars.set(k, v);
    for (const [token, role] of FOREGROUNDS) {
      const hex = resolve(vars, token);
      rows.push({ scheme, token, role, hex, ratios: Object.fromEntries(SURFACES.map(([s]) => [s, ratio(hex, resolve(vars, s))])) });
    }
  }
  return rows;
}

const mark = (r: number) => (r >= 4.5 ? `${r.toFixed(2)}` : r >= 3 ? `${r.toFixed(2)} (large/UI only)` : `**${r.toFixed(2)} fails**`);

export function markdown(rows: Row[]): string {
  const head = `| Token | Role | Hex | ${SURFACES.map(([t, r]) => `on ${r} \`${t}\``).join(" | ")} |\n|---|---|---|${SURFACES.map(() => "---").join("|")}|`;
  const table = (scheme: string) => rows.filter((r) => r.scheme === scheme).map((r) => `| \`${r.token}\` | ${r.role} | \`${r.hex}\` | ${SURFACES.map(([s]) => mark(r.ratios[s])).join(" | ")} |`).join("\n");
  return `# Palette contrast

Generated by \`node scripts/design/contrast.ts\` from \`src/theme.css\` and
\`src/layout.css\`; \`test/fixtures/design/contrast.test.ts\` fails when this file
no longer matches them. Do not edit by hand.

WCAG 2.2 ratios of each text and mark colour on each surface, Night (the
default, dark) and its light variant (\`prefers-color-scheme: light\`). Normal
text needs 4.5:1 (1.4.3); large text (24 px, or 18.66 px bold) and
non-text marks such as graph lines and the focus ring need 3:1 (1.4.11).
This is the palette, not a page: a token can pass here and still fail where
it is drawn with opacity, over a tint, or on a gradient. The rendered
measurements are in \`docs/design/audit.json\`, written by the capture.

## Night (dark)

${head}
${table("dark")}

## Light

${head}
${table("light")}
`;
}

export function current(): string {
  return markdown(measure(readFileSync(`${ROOT}/src/theme.css`, "utf8"), readFileSync(`${ROOT}/src/layout.css`, "utf8")));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(`${ROOT}/docs/design/contrast.md`, current());
  console.log("wrote docs/design/contrast.md");
}
